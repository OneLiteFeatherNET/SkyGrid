// The Paper plugin: everything that talks to Bukkit or Paper. It holds the driving and driven adapters
// (generator, spawn, command, config, persistence), the Bukkit composition root (SkyGridNgPlugin,
// i18n, Guice modules) and the platform-specific packaging (shaded jar, plugin.yml, run-paper,
// SBOM). It depends on the framework-free domain module, which it wires to the platform. Bukkit,
// Adventure and the Paper API are compileOnly because the server provides them at runtime.
dependencies {
    implementation(project(":domain"))

    compileOnly(libs.paper.api)
    compileOnly(libs.adventure.api)
    // MiniMessage parses admin-authored season display names (MiniMessage tags) into components.
    compileOnly(libs.adventure.minimessage)

    // Configuration: Jackson databind plus the YAML dataformat, the only config format. Bundled and
    // relocated in the shaded jar.
    implementation(libs.jackson.databind)
    implementation(libs.jackson.yaml)

    // Persistence: Jakarta Persistence via Hibernate ORM, Hibernate's own Hikari pool, Flyway migrations
    // and the PostgreSQL driver. jakarta.persistence and org.hibernate types stay inside the adapters.
    implementation(libs.postgresql)
    implementation(libs.hikaricp)
    implementation(libs.flyway.core)
    implementation(libs.flyway.postgresql)
    implementation(libs.hibernate.hikaricp)
    // api, not implementation: the ArchUnit module (verification) compiles against these types.
    api(libs.jakarta.persistence.api)
    api(libs.hibernate.core)
    // Entities of the one persistence unit, which compile here with their static metamodel generated by Hibernate.
    annotationProcessor(libs.hibernate.jpamodelgen)

    // Cloud command framework: the platform-neutral core and annotations, plus the Paper/Bukkit binding
    // (CloudCommandManagerFactory, PaperCommandSource, CloudCommandRegistrar).
    implementation(libs.cloud.core)
    implementation(libs.cloud.annotations)
    implementation(libs.cloud.paper)

    // Dependency injection, bundled and relocated where it is a library the server does not provide.
    implementation(libs.guice)
    implementation(libs.jakarta.inject)

    testImplementation(testFixtures(project(":domain")))
    testImplementation(libs.junit.jupiter)
    testRuntimeOnly(libs.junit.launcher)
    // Paper API is compileOnly for main, so tests need it explicitly (MockBukkit does not export it).
    testImplementation(libs.paper.api)
    testImplementation(libs.mockbukkit)
    testImplementation(libs.mockito.core)
    testImplementation(libs.assertj.core)
    testImplementation(libs.adventure.api)
    testImplementation(libs.adventure.minimessage)
    testImplementation(libs.testcontainers.postgresql)
    testImplementation(libs.testcontainers.junit.jupiter)
}

tasks {
    shadowJar {
        // Keep the published artifact name stable (skygrid-ng-<version>.jar) regardless of the
        // producing module path (plugin).
        archiveBaseName.set("skygrid-ng")
        archiveClassifier.set("")
        // Relocate Jackson (and the SnakeYAML its YAML backend pulls in) so they cannot clash with
        // the copies the server or another plugin ships. Bukkit bundles its own SnakeYAML.
        relocate("com.fasterxml.jackson", "net.onelitefeather.skygridng.libs.jackson")
        relocate("org.yaml.snakeyaml", "net.onelitefeather.skygridng.libs.snakeyaml")
        // Hibernate pulls in classmate transitively; relocate it so it cannot clash with another copy.
        relocate("com.fasterxml.classmate", "net.onelitefeather.skygridng.libs.classmate")
        // Incendo Cloud is a popular command framework other plugins may also shade; relocate it so
        // two differently-versioned copies on the same server cannot clash on the classpath.
        relocate("org.incendo.cloud", "net.onelitefeather.skygridng.libs.cloud")
        // Shadow drops duplicate entries before service files are merged, which kept only the first
        // jar's META-INF/services file (Flyway would lose its core plugin). Let them through here.
        filesMatching("META-INF/services/**") {
            duplicatesStrategy = DuplicatesStrategy.INCLUDE
        }
        mergeServiceFiles()
    }

    test {
        // ShadowJarServiceFilesTest checks the merged service files of the jar the server loads.
        dependsOn(shadowJar)
        val shadowJarFile = shadowJar.flatMap { it.archiveFile }
        jvmArgumentProviders.add(CommandLineArgumentProvider {
            listOf("-Dskygrid.shadowJar=${shadowJarFile.get().asFile.absolutePath}")
        })
    }

    build {
        dependsOn(shadowJar)
    }

    withType<RunServer> {
        minecraftVersion("26.1.2")
    }
}

