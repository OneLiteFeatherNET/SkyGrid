package net.onelitefeather.skygridng.platforms.olf;

import com.google.inject.AbstractModule;
import com.google.inject.Provides;
import com.google.inject.multibindings.Multibinder;
import com.google.inject.multibindings.OptionalBinder;
import jakarta.inject.Singleton;
import net.onelitefeather.skygridng.adapters.challenge.ChallengeBehavior;
import net.onelitefeather.skygridng.adapters.challenge.LevelBorderWarningTask;
import net.onelitefeather.skygridng.adapters.challenge.NoCraftingTableListener;
import net.onelitefeather.skygridng.adapters.challenge.NoNaturalRegenerationListener;
import net.onelitefeather.skygridng.adapters.challenge.OneLifeListener;
import net.onelitefeather.skygridng.adapters.config.BundledDefaults;
import net.onelitefeather.skygridng.adapters.config.JacksonChallengeRepository;
import net.onelitefeather.skygridng.adapters.generator.HexagonalChunkGenerator;
import net.onelitefeather.skygridng.core.service.ChallengeAdminService;
import net.onelitefeather.skygridng.core.state.ChallengeState;
import net.onelitefeather.skygridng.ports.in.ChallengeAdminUseCase;
import net.onelitefeather.skygridng.ports.out.ChallengeRepository;
import org.bukkit.World;
import org.bukkit.plugin.java.JavaPlugin;

import java.nio.file.Path;
import java.util.function.Predicate;

/**
 * OLF-only Guice module: wires the challenge mechanic (the Jackson-backed repository, the shared
 * state, the admin service, and every {@link ChallengeBehavior}), and sets the
 * {@link ChallengeAdminUseCase} optional binding that {@code GeneratorModule} leaves absent on the
 * public distribution. Layered on top of the base wiring by {@link OlfNetworkPlugin}, so it is
 * present only in this jar.
 */
final class ChallengeModule extends AbstractModule {

    @Override
    protected void configure() {
        OptionalBinder.newOptionalBinder(binder(), ChallengeAdminUseCase.class)
                .setBinding().to(ChallengeAdminService.class);

        Multibinder<ChallengeBehavior> behaviors = Multibinder.newSetBinder(binder(), ChallengeBehavior.class);
        behaviors.addBinding().to(NoCraftingTableListener.class);
        behaviors.addBinding().to(OneLifeListener.class);
        behaviors.addBinding().to(NoNaturalRegenerationListener.class);
        behaviors.addBinding().to(LevelBorderWarningTask.class);
    }

    @Provides
    @Singleton
    ChallengeRepository provideChallengeRepository(JavaPlugin plugin, Path dataFolder) {
        BundledDefaults defaults = plugin::getResource;
        return new JacksonChallengeRepository(dataFolder, defaults);
    }

    @Provides
    @Singleton
    ChallengeState provideChallengeState(ChallengeRepository repository) {
        return new ChallengeState(repository.load());
    }

    @Provides
    @Singleton
    ChallengeAdminService provideChallengeAdminService(ChallengeState state, ChallengeRepository repository) {
        return new ChallengeAdminService(state, repository);
    }

    /**
     * Shared scoping predicate for every {@link ChallengeBehavior}: true for worlds generated by
     * SkyGrid-ng, mirroring how {@code PlatformModule} scopes the spread-spawn listener. Every
     * behavior's constructor takes this same instance instead of rebuilding it.
     */
    @Provides
    @Singleton
    Predicate<World> provideSkyGridWorldPredicate() {
        return world -> world.getGenerator() instanceof HexagonalChunkGenerator;
    }
}
