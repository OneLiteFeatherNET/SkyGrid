package net.onelitefeather.skygridng.platforms.common.injection;

import com.google.inject.AbstractModule;
import com.google.inject.Provides;
import jakarta.inject.Singleton;
import net.onelitefeather.skygridng.platforms.common.generator.HexagonalChunkGenerator;
import net.onelitefeather.skygridng.platforms.common.spawn.SpreadSpawnListener;
import net.onelitefeather.skygridng.ports.in.SpawnPoints;
import org.bukkit.plugin.java.JavaPlugin;

import java.nio.file.Path;

/**
 * Binds the Bukkit platform into the object graph: the plugin instance and its data folder.
 *
 * Keeping the platform in its own module mirrors the OneLiteFeather convention and isolates the
 * only module that needs a constructor argument.
 */
public final class PlatformModule extends AbstractModule {

    private final JavaPlugin plugin;

    public PlatformModule(JavaPlugin plugin) {
        this.plugin = plugin;
    }

    @Override
    protected void configure() {
        bind(JavaPlugin.class).toInstance(plugin);
    }

    @Provides
    @Singleton
    Path provideDataFolder(JavaPlugin plugin) {
        return plugin.getDataFolder().toPath();
    }

    /**
     * The spread-spawn listener, scoped to worlds generated by SkyGrid-ng so it never touches a
     * vanilla or other-plugin world. The world check lives here (not in the adapter) because it is
     * the composition root that knows which generator is ours.
     */
    @Provides
    @Singleton
    SpreadSpawnListener provideSpreadSpawnListener(JavaPlugin plugin, SpawnPoints spawnPoints) {
        return new SpreadSpawnListener(plugin, spawnPoints,
                world -> world.getGenerator() instanceof HexagonalChunkGenerator);
    }
}
