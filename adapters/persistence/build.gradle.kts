// Shared driven-adapter infrastructure: the reusable Jakarta Persistence (JSR 338) via Hibernate
// ORM bootstrap of the one shared Postgres database (Database), so a new repository needs only its own
// @Entity class (listed in the one persistence unit), a migration, and a small repository on the shared
// Database, not a second pool or a second copy of the factory-bootstrap/transaction-lifecycle plumbing. This module compiles
// against the ports and the public api only, never core, per the project's hexagonal dependency
// rule. Persistence is bootstrapped standalone (no Spring/Micronaut/application server) through the
// standard Persistence.createEntityManagerFactory entry point; Hibernate owns the HikariCP
// connection pool directly (hibernate-hikaricp). Schema ownership (versioned Flyway migrations,
// never a hand-edited CREATE TABLE assumed to match the code) is left to each concrete adapter's own
// one persistence unit and one migration history (db/migration); this module owns the shared Database
// with its lazy bootstrap and transaction helpers that every repository uses.
// jakarta.persistence, org.hibernate, java.sql, HikariCP and Flyway types stay entirely inside this
// module and the adapters that depend on it; they never leak into ports, api or core.
dependencies {
    implementation(project(":ports"))
    implementation(project(":api"))

    implementation(libs.postgresql)
    implementation(libs.hikaricp)
    implementation(libs.flyway.core)
    implementation(libs.flyway.postgresql)
    implementation(libs.hibernate.hikaricp)

    // Exposed with the api configuration (not implementation): Database's read/inTransaction methods take
    // a jakarta.persistence.EntityManager, and a repository (for example PostgresChallengeProgressRepository)
    // typically also needs Hibernate-specific exception types (ConstraintViolationException) directly at
    // compile time. Declaring these as api here means a dependent module only needs
    // implementation(project(":adapters:persistence")), not a repeated copy of these library coordinates.
    api(libs.jakarta.persistence.api)
    api(libs.hibernate.core)

    // Entities of the one persistence unit, which compile here with their static metamodel generated by Hibernate.
    annotationProcessor(libs.hibernate.jpamodelgen)

    testImplementation(libs.junit.jupiter)
    testRuntimeOnly(libs.junit.launcher)
    testImplementation(libs.assertj.core)
    testImplementation(libs.testcontainers.postgresql)
    testImplementation(libs.testcontainers.junit.jupiter)
}
